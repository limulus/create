import { describe, expect, it } from 'vitest'

import {
  createArguments,
  OWNER,
  packedPackage,
  stepFault,
  unpackedTemplates,
  VARIANTS,
  withoutNpmConfig,
  type Packed,
} from './skeleton.ts'

const packed: Packed = {
  name: '@scope/create',
  version: '1.2.3',
  filename: 'scope-create-1.2.3.tgz',
  files: [
    { path: 'package.json' },
    { path: 'skel/.gitignore.mustache' },
    { path: 'skel/package.json.mustache' },
  ],
}

describe('VARIANTS', () => {
  it('should cover every combination of privacy and target', () => {
    const combinations = VARIANTS.map(({ options }) => [
      options.includes('--public'),
      options[options.indexOf('--target') + 1],
    ])
    expect(combinations).toEqual([
      [false, 'node'],
      [false, 'web'],
      [true, 'node'],
      [true, 'web'],
    ])
  })

  it('should give every variant a scoped name, since an unscoped one is always public', () => {
    for (const { name } of VARIANTS) expect(name).toMatch(/^@[^/]+\//)
  })

  it('should give each variant its own label', () => {
    expect(new Set(VARIANTS.map(({ label }) => label)).size).toBe(VARIANTS.length)
  })
})

describe('createArguments()', () => {
  it('should pass the name, a description, the options and the owner', () => {
    const variant = { label: 'x', name: '@scratch/x', options: ['--public'] }
    expect(createArguments(variant)).toEqual([
      '@scratch/x',
      'The x variant, generated by test:skel',
      '--public',
      '--owner',
      OWNER,
    ])
  })
})

describe('packedPackage()', () => {
  it('should return the single package of a report', () => {
    expect(packedPackage([packed])).toBe(packed)
  })

  it('should throw when the report holds no package', () => {
    expect(() => packedPackage([])).toThrow('npm pack reported [], not one package')
  })

  it('should throw when the report holds more than one package', () => {
    expect(() => packedPackage([packed, packed])).toThrow(/not one package/)
  })

  it('should throw when the report is not a list', () => {
    expect(() => packedPackage({ error: 'nope' })).toThrow(
      'npm pack reported {"error":"nope"}, not one package'
    )
  })
})

describe('unpackedTemplates()', () => {
  it('should find nothing missing when every template shipped', () => {
    const tracked = ['skel/.gitignore.mustache', 'skel/package.json.mustache']
    expect(unpackedTemplates(tracked, packed)).toEqual([])
  })

  it('should name a template the tarball dropped', () => {
    const tracked = [
      'skel/.gitignore.mustache',
      'skel/.npmrc',
      'skel/package.json.mustache',
    ]
    expect(unpackedTemplates(tracked, packed)).toEqual([
      'skel/.npmrc is in the repository but not in the packed tarball',
    ])
  })
})

describe('stepFault()', () => {
  it('should find no fault in a step that exited 0', () => {
    expect(stepFault({ status: 0, signal: null })).toBeNull()
  })

  it('should give the exit status of a step that failed', () => {
    expect(stepFault({ status: 1, signal: null })).toBe('exited 1')
  })

  it('should name the signal that killed a step', () => {
    expect(stepFault({ status: null, signal: 'SIGTERM' })).toBe('was killed by SIGTERM')
  })

  it('should give the error when a step could not start', () => {
    const error = new Error('spawnSync npx ENOENT')
    expect(stepFault({ status: null, signal: null, error })).toBe(
      'could not run: spawnSync npx ENOENT'
    )
  })
})

describe('withoutNpmConfig()', () => {
  it('should drop npm’s own variables, whatever their case, and keep the rest', () => {
    const env = {
      PATH: '/bin',
      HOME: undefined,
      npm_config_local_prefix: '/repo',
      npm_package_name: '@scope/create',
      NPM_CONFIG_USERCONFIG: '/home/.npmrc',
    }
    expect(withoutNpmConfig(env)).toEqual({ PATH: '/bin', HOME: undefined })
  })
})
