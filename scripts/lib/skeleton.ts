/**
 * The decisions behind `npm run test:skel`: which projects it generates, what the packed
 * tarball must hold, and how to read `npm pack`'s report. The script around them is I/O:
 * pack, generate, install, verify. The deciding is here, where a spec can feed it a
 * violation.
 */

/** A project the check generates, with the `create` options that select its templates. */
export interface Variant {
  label: string
  name: string
  options: string[]
}

/**
 * Every combination of the template axes: privacy changes `package.json`, `LICENSE` and
 * the publish job in `cd.yaml`; the target changes the tsconfig module settings.
 */
export const VARIANTS: readonly Variant[] = [
  { label: 'private-node', name: '@scratch/private-node', options: ['--target', 'node'] },
  { label: 'private-web', name: '@scratch/private-web', options: ['--target', 'web'] },
  {
    label: 'public-node',
    name: '@scratch/public-node',
    options: ['--target', 'node', '--public'],
  },
  {
    label: 'public-web',
    name: '@scratch/public-web',
    options: ['--target', 'web', '--public'],
  },
]

/**
 * The scratch repositories have no `origin` remote, so the GitHub owner is named by hand.
 * It matches the variants' scope, which `create` requires of a private package.
 */
export const OWNER = 'scratch'

/** The arguments `create` receives for a variant. */
export function createArguments(variant: Variant): string[] {
  return [
    variant.name,
    `The ${variant.label} variant, generated by test:skel`,
    ...variant.options,
    '--owner',
    OWNER,
  ]
}

/** A package as `npm pack --json` reports it. */
export interface Packed {
  name: string
  version: string
  filename: string
  files: { path: string }[]
}

/**
 * The one package `npm pack --json` reported packing. Throws when the report is not a
 * single package, since every later step depends on that tarball.
 */
export function packedPackage(report: unknown): Packed {
  if (!Array.isArray(report) || report.length !== 1) {
    throw new Error(`npm pack reported ${JSON.stringify(report)}, not one package`)
  }
  return report[0] as Packed
}

/**
 * Each template in the repository that the tarball lacks, one sentence each; none when
 * all of them shipped. `npm pack` drops or renames some dotfiles (`.gitignore`, `.npmrc`),
 * and a generated project would then be silently without them.
 */
export function unpackedTemplates(
  tracked: readonly string[],
  packed: Pick<Packed, 'files'>
): string[] {
  const paths = new Set(packed.files.map(({ path }) => path))
  return tracked
    .filter((path) => !paths.has(path))
    .map((path) => `${path} is in the repository but not in the packed tarball`)
}

/** How a step's child process ended, as `spawnSync` reports it. */
export interface StepResult {
  status: number | null
  signal: string | null
  error?: Error
}

/**
 * Why a step failed, or `null` when it exited 0. `status` alone is `null` both when a
 * signal killed the child and when it never started, and neither says which.
 */
export function stepFault(result: StepResult): string | null {
  if (result.error) return `could not run: ${result.error.message}`
  if (result.signal !== null) return `was killed by ${result.signal}`
  if (result.status !== 0) return `exited ${result.status}`
  return null
}

/**
 * The environment without the `npm_*` variables npm hands a script about its own run.
 * The check runs npm in other projects, where that configuration does not belong.
 */
export function withoutNpmConfig(
  env: Readonly<Record<string, string | undefined>>
): Record<string, string | undefined> {
  return Object.fromEntries(
    Object.entries(env).filter(([name]) => !name.toLowerCase().startsWith('npm_'))
  )
}
